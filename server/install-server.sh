#!/usr/bin/env bash
# Install only on the Debian/Ubuntu machine you intend to use as your VPN exit.
set -euo pipefail
umask 077

usage() {
    cat <<'USAGE'
Usage: sudo bash server/install-server.sh --config /path/to/wg0.conf [--interface eth0]

Installs signed distribution packages, a new managed wg0 tunnel, IPv4 NAT and
forwarding, and a systemd service. Refuses unrelated existing wg0 configuration
and active UFW/firewalld. This changes the selected server's network firewall.
Use a spare VM for your first test. See docs/server.md before running.
USAGE
}
die() { echo "Error: $*" >&2; exit 1; }

# Do not run a supplied wg-quick file unchecked: hooks can execute root commands.
# Accept the generated one-client configuration only, and reject unknown fields.
validate_config() {
    awk '
    function bad() { invalid=1; exit 1 }
    function trim(s) { sub(/^[ \t]+/, "", s); sub(/[ \t]+$/, "", s); return s }
    {
      sub(/\r$/, ""); line=trim($0)
      if (line=="" || line ~ /^#/) next
      if (line=="[Interface]") { if (section!="" || ++interfaces!=1) bad(); section="interface"; next }
      if (line=="[Peer]") { if (section!="interface" || ++peers!=1) bad(); section="peer"; next }
      equal=index(line,"="); if (!equal) bad()
      field=trim(substr(line,1,equal-1)); value=trim(substr(line,equal+1))
      if (++seen[section SUBSEP field]!=1) bad()
      if (section=="interface" && field=="Address") { gsub(/[ \t]/,"",value); if (value!="10.66.66.1/24,fd66:66:66::1/64") bad(); address=1 }
      else if (section=="interface" && field=="ListenPort") { if(value !~ /^[0-9]+$/ || length(value)>5 || value+0<1 || value+0>65535) bad(); port=1 }
      else if (section=="interface" && field=="PrivateKey") { if(length(value)!=44 || value !~ /^[A-Za-z0-9+\/]+=$/) bad(); privatekey=1 }
      else if (section=="peer" && field=="PublicKey") { if(length(value)!=44 || value !~ /^[A-Za-z0-9+\/]+=$/) bad(); publickey=1 }
      else if (section=="peer" && field=="AllowedIPs") { gsub(/[ \t]/,"",value); if(value!="10.66.66.2/32,fd66:66:66::2/128") bad(); allowed=1 }
      else bad()
    }
    END { if(invalid || interfaces!=1 || peers!=1 || !address || !port || !privatekey || !publickey || !allowed) exit 1 }
    ' "$1"
}

main() {
    local config='' uplink='' listen_port=''
    while (( $# )); do
        case $1 in
            --config) (( $# >= 2 )) || die '--config requires a file.'; config=$2; shift 2 ;;
            --interface) (( $# >= 2 )) || die '--interface requires a name.'; uplink=$2; shift 2 ;;
            -h|--help) usage; return 0 ;;
            *) usage >&2; die 'Unknown argument.' ;;
        esac
    done
    [[ -n $config && -f $config ]] || die 'Provide an existing generated wg0.conf using --config.'
    validate_config "$config" || die 'Unsupported wg0.conf. Use the unmodified server file generated by MyVPN; hooks and arbitrary directives are rejected.'
    listen_port=$(awk '/^[ \t]*ListenPort[ \t]*=/ { sub(/^[^=]*=[ \t]*/, ""); sub(/[ \t\r]*$/, ""); print $0 }' "$config")
    (( EUID == 0 )) || die 'Run with sudo on your chosen Linux VPN server.'
    [[ -f /etc/os-release ]] || die 'Cannot identify the server distribution.'
    # shellcheck source=/dev/null
    . /etc/os-release
    [[ $ID == debian || $ID == ubuntu ]] || die 'This installer supports Debian and Ubuntu only.'
    command -v systemctl >/dev/null || die 'A running systemd installation is required; use a VM, not a plain container.'
    [[ $(ps -p 1 -o comm=) == systemd ]] || die 'systemd must be the server init process.'
    if command -v ufw >/dev/null; then
        local ufw_status
        ufw_status=$(LC_ALL=C ufw status) || die 'Cannot read UFW status; inspect that firewall before installing.'
        if [[ $ufw_status == 'Status: active'* ]]; then
            die 'UFW is active. Keep it enabled and use the manual firewall instructions in docs/server.md.'
        fi
    fi
    if systemctl is-active --quiet firewalld; then
        die 'firewalld is active. Keep it enabled and configure WireGuard through that manager; see docs/server.md.'
    fi
    command -v ip >/dev/null || die 'iproute2 is required to identify the uplink.'
    if [[ -z $uplink ]]; then
        uplink=$(ip -4 route get 1.1.1.1 | awk '{ for(i=1;i<=NF;i++) if($i=="dev") {print $(i+1); exit} }')
    fi
    [[ $uplink =~ ^[a-zA-Z0-9_.:-]{1,15}$ && $uplink != wg0 ]] || die 'Cannot determine a safe IPv4 uplink; supply --interface.'
    ip link show dev "$uplink" >/dev/null 2>&1 || die 'The selected uplink does not exist.'

    local source_dir target=/etc/wireguard/wg0.conf helper=/usr/local/lib/myvpn/firewall.sh
    local state=/var/lib/myvpn sysctl_file=/etc/sysctl.d/70-myvpn-forwarding.conf
    source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
    [[ -f $source_dir/myvpn-firewall.sh ]] || die 'Keep myvpn-firewall.sh beside this installer.'
    local path
    for path in /etc/wireguard /usr/local/lib/myvpn "$state" "$target" "$helper" "$sysctl_file"; do
        [[ ! -L $path ]] || die 'Refusing to write through a symlink in a managed path.'
        if [[ -e $path ]]; then
            [[ $(stat -c %u "$path") == 0 ]] || die 'An existing managed path is not root-owned; it was preserved.'
            local path_mode
            path_mode=$(stat -c %a "$path")
            (( (8#$path_mode & 0022) == 0 )) || die 'An existing managed path is writable by other users; it was preserved.'
        fi
    done
    local managed=false
    if [[ -f $state/managed-v1 ]]; then
        managed=true
    elif [[ -e $state || -e $target || -e /usr/local/lib/myvpn || -e $sysctl_file ]] || ip link show dev wg0 >/dev/null 2>&1; then
        die 'Existing wg0/MyVPN files or interface were found. Nothing was overwritten; use a fresh VM or handle that existing installation separately.'
    fi

    local stage
    stage=$(mktemp -d)
    MYVPN_SERVER_STAGE=$stage
    trap 'rm -rf -- "$MYVPN_SERVER_STAGE"' EXIT
    # Normalize CRLF from Windows without printing key material.
    sed 's/\r$//' "$config" > "$stage/wg0.conf"
    printf '\n# MyVPN managed hooks\nPostUp = %s up %%i %s %s\nPostDown = %s down %%i %s %s\n' "$helper" "$uplink" "$listen_port" "$helper" "$uplink" "$listen_port" > "$stage/hooks"
    # Hooks belong in [Interface], before [Peer].
    awk -v hooks="$stage/hooks" '/^[ \t]*\[Peer\][ \t]*$/ { while ((getline line < hooks)>0) print line; close(hooks) } { print }' "$stage/wg0.conf" > "$stage/installed.conf"
    printf 'net.ipv4.ip_forward = 1\n' > "$stage/sysctl.conf"
    if [[ $managed == true ]]; then
        [[ -f $target && -f $helper && -f $sysctl_file ]] || die 'Managed installation is incomplete; inspect it before reinstalling.'
        cmp -s "$stage/installed.conf" "$target" || die 'Existing server configuration differs. It was preserved; deliberate key/configuration changes need a separate migration.'
        cmp -s "$source_dir/myvpn-firewall.sh" "$helper" || die 'Existing managed firewall helper differs. It was preserved; inspect before updating.'
        cmp -s "$stage/sysctl.conf" "$sysctl_file" || die 'Existing forwarding configuration differs. It was preserved.'
    fi

    # Package signatures and TLS checks stay enabled. Do not pipe an internet
    # installer into a shell or use --allow-unauthenticated.
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends wireguard-tools iptables iproute2
    if [[ $managed == false ]]; then
        install -d -m 0700 /etc/wireguard "$state"
        install -d -m 0755 /usr/local/lib/myvpn
        install -m 0600 "$stage/installed.conf" "$target"
        install -m 0755 "$source_dir/myvpn-firewall.sh" "$helper"
        install -m 0644 "$stage/sysctl.conf" "$sysctl_file"
        printf 'MyVPN managed installation v1\n' > "$state/managed-v1"
    fi
    sysctl -p "$sysctl_file" >/dev/null
    # Idempotent reruns enable/start a stopped service without disconnecting an
    # already active connection. Reboot repeats the wg-quick firewall hooks.
    systemctl enable --now wg-quick@wg0
    systemctl is-active --quiet wg-quick@wg0 || die 'wg-quick did not start. Inspect sudo journalctl -u wg-quick@wg0.'
    wg show wg0 >/dev/null || die 'The service started but the WireGuard interface could not be queried.'
    printf '\nServer installed. UDP listener: %s. Tunnel IPv4: 10.66.66.1\n' "$listen_port"
    printf 'Allow inbound UDP %s in any external/cloud firewall and router.\n' "$listen_port"
    printf 'Connect the Windows client, then check: sudo wg show wg0 latest-handshakes\n'
    printf 'A running service is not proof of a client connection; complete docs/server.md checks.\n'
}

# Allow tests to source the validator without executing privileged operations.
if [[ ${BASH_SOURCE[0]} == "$0" ]]; then main "$@"; fi
